create table if not exists public.homebase_agent_memory (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  memory_key text not null,
  memory_type text not null check (memory_type in ('preference','goal','constraint','lesson','fact','strategy')),
  content jsonb not null default '{}'::jsonb,
  confidence numeric not null default 0.7 check (confidence >= 0 and confidence <= 1),
  source text not null default 'conversation',
  active boolean not null default true,
  learned_at timestamptz not null default now(),
  last_used_at timestamptz,
  unique (user_id, memory_key)
);
create index if not exists homebase_agent_memory_user_active_idx on public.homebase_agent_memory (user_id, active, learned_at desc);

create table if not exists public.homebase_agent_turns (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  conversation_id text not null,
  role text not null check (role in ('user','assistant')),
  content text not null,
  context jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists homebase_agent_turns_user_conversation_idx on public.homebase_agent_turns (user_id, conversation_id, created_at desc);

alter table public.homebase_agent_memory enable row level security;
alter table public.homebase_agent_turns enable row level security;
do $$ begin
